static void set_error(char *error, size_t cap, const char *message) {
    if (error && cap) snprintf(error, cap, "%s", message ? message : "unknown quant-table error");
}

static int hex_nibble(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return 10 + c - 'a';
    if (c >= 'A' && c <= 'F') return 10 + c - 'A';
    return -1;
}

static int expand_grid(
        const char *hex,
        const int8_t map[3],
        int8_t *out,
        size_t expected,
        char *error,
        size_t error_cap) {
    const size_t hex_len = strlen(hex);
    if ((hex_len & 1u) || (hex_len / 2u) * 4u != expected) {
        set_error(error, error_cap, "native quant grid compact-size mismatch");
        return 0;
    }
    size_t pos = 0;
    for (size_t i = 0; i < hex_len; i += 2) {
        const int hi = hex_nibble(hex[i]);
        const int lo = hex_nibble(hex[i + 1]);
        if (hi < 0 || lo < 0) {
            set_error(error, error_cap, "native quant grid contains non-hex data");
            return 0;
        }
        const unsigned byte = (unsigned)((hi << 4) | lo);
        for (unsigned shift = 0; shift < 8; shift += 2) {
            const unsigned code = (byte >> shift) & 3u;
            if (code >= 3u || pos >= expected) {
                set_error(error, error_cap, "native quant grid contains invalid 2-bit code");
                return 0;
            }
            out[pos++] = map[code];
        }
    }
    if (pos != expected) {
        set_error(error, error_cap, "native quant grid expansion length mismatch");
        return 0;
    }
    return 1;
}

int rl_native_quant_tables_init(
        rl_native_quant_tables *tables,
        char *error,
        size_t error_cap) {
    if (!tables) {
        set_error(error, error_cap, "native quant table output is null");
        return 0;
    }
    memset(tables, 0, sizeof(*tables));
    tables->iq2_xs = (int8_t *)malloc(RL_IQ2_XS_GRID_COUNT);
    tables->iq1_m = (int8_t *)malloc(RL_IQ1_M_GRID_COUNT);
    if (!tables->iq2_xs || !tables->iq1_m) {
        rl_native_quant_tables_free(tables);
        set_error(error, error_cap, "out of memory expanding native quant grids");
        return 0;
    }
    const int8_t iq2_map[3] = {0x08, 0x19, 0x2b};
    const int8_t iq1_map[3] = {-1, 0, 1};
    if (!expand_grid(k_iq2_xs_grid_hex, iq2_map, tables->iq2_xs,
                     RL_IQ2_XS_GRID_COUNT, error, error_cap) ||
        !expand_grid(k_iq1_m_grid_hex, iq1_map, tables->iq1_m,
                     RL_IQ1_M_GRID_COUNT, error, error_cap)) {
        rl_native_quant_tables_free(tables);
        return 0;
    }
    if (tables->iq2_xs[0] != 0x08 || tables->iq2_xs[RL_IQ2_XS_GRID_COUNT - 1] != 0x2b ||
        tables->iq1_m[0] != -1 || tables->iq1_m[RL_IQ1_M_GRID_COUNT - 1] != 1) {
        rl_native_quant_tables_free(tables);
        set_error(error, error_cap, "native quant grid sentinel validation failed");
        return 0;
    }
    if (error && error_cap) error[0] = '\0';
    return 1;
}

void rl_native_quant_tables_free(rl_native_quant_tables *tables) {
    if (!tables) return;
    free(tables->iq2_xs);
    free(tables->iq1_m);
    memset(tables, 0, sizeof(*tables));
}

uint64_t rl_native_quant_table_fnv1a(const int8_t *data, size_t count) {
    uint64_t hash = 1469598103934665603ull;
    if (!data) return hash;
    for (size_t i = 0; i < count; ++i) {
        hash ^= (uint8_t)data[i];
        hash *= 1099511628211ull;
    }
    return hash;
}
